#!/usr/bin/env python3
"""Extract Vibresia's built-in scenes into a JavaScript module.

Vibresia keeps its scene bodies in VisualiserMac/Sources/VisualiserMac/Render/
FunShaders.swift as Swift string literals. Each is a full fragment shader that
writes fragColor in its main(), and each is drawn on top of the shared
prelude. Parachord draws them with the same contract, so it needs the bodies
as text.

This reads the Swift file and writes src/renderer/lib/vibresia-scenes.js. The
copy is deliberate: the scenes belong to Vibresia, and Parachord is a separate
app with its own release cycle, so it carries its own copy rather than
fetching one at runtime. The scenes are MIT-licensed, like the rest of
Vibresia.

  python3 scripts/extract-vibresia-scenes.py <vibresia-repo>
"""
import os
import re
import sys

# The scenes Parachord ships, in the order Vibresia's app lists them. Each is
# a `static let <slug>` in FunShaders.swift.
SCENES = [
    ("ribbons", "RIBBONS", "Luminous ribbons twisting through floating glass shapes."),
    ("vortex", "VORTEX", "A cyber tunnel of grid lines rushing past, twisting with the bass."),
    ("spectrum", "SPECTRUM", "Classic segmented LED bars with falling peak caps."),
    ("kaleidoscope", "KALEIDOSCOPE", "Mirrored fractal folds that punch in on the bass."),
    ("warp", "WARP", "Hyperspace star streaks trailing behind the music."),
    ("waveform", "NEON WAVE", "Glowing waveforms shaped by the spectrum."),
    ("silk", "SILK FLIGHT", "A satin ribbon twisting away into a dust cloud, with glass blocks tumbling by."),
    ("flux", "FLUX", "Sheets of hot pink and gold light swirling into a vanishing point."),
    ("danceFloor", "DANCE FLOOR", "A perspective grid of neon Rubik's-cube tiles that re-solve to the beat."),
    ("nyan", "NYAN CAT", "A pixel cat on a rainbow trail streaking across the screen."),
    ("hamster", "HAMSTER DANCE", "A wall of pixel hamsters dancing at the song's tempo."),
    ("badger", "BADGER BADGER", "Rows of dancing badgers, in time with the beat."),
    ("llama", "WHOOPING LLAMA", "Llamas in bright blankets hopping on the beat."),
]

HEADER = """// src/renderer/lib/vibresia-scenes.js — Vibresia's scenes, for the built-in
// visualiser.
//
// Each scene is a full fragment shader that writes fragColor in its main(),
// and is drawn on top of the shared prelude in vibresia-visualizer.js. They
// are Vibresia's own, copied from its source (FunShaders.swift) by
// scripts/extract-vibresia-scenes.py. Vibresia is MIT-licensed, like
// Parachord, and the copy is here rather than fetched at runtime because
// Parachord has its own release cycle and a visualiser that needs the network
// to draw would be a poor neighbour.
//
// GENERATED by scripts/extract-vibresia-scenes.py — edit the Swift source
// and re-run, rather than editing this file.

'use strict';

const SCENES = [
"""


def swift_block(src, name):
    """The body of `static let <name> = \"\"\"...\"\"\"`, dedented."""
    m = re.search(r'static let ' + re.escape(name) + r' = """\n(.*?)\n    """', src, re.S)
    if not m:
        raise SystemExit(f"FunShaders.swift has no `static let {name}`")
    body = m.group(1)
    return "\n".join(l[4:] if l.startswith("    ") else l for l in body.split("\n"))


def js_string(text):
    """A JS single-quoted string, with the characters that need escaping."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def js_template(text):
    """A JS template literal holding GLSL.

    The GLSL is embedded in backticks, so the two characters that would end
    the literal early have to be escaped: the backtick itself, and the ${}
    that starts an interpolation. A backslash has to be escaped too, so it
    does not escape the next character.
    """
    return (
        "`"
        + text.replace("\\", "\\\\")
        .replace("`", "\\`")
        .replace("${", "\\${")
        + "`"
    )


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: extract-vibresia-scenes.py <vibresia-repo>")
    root = sys.argv[1]
    fun = os.path.join(root, "VisualiserMac/Sources/VisualiserMac/Render/FunShaders.swift")
    if not os.path.exists(fun):
        raise SystemExit(f"missing {fun}")
    src = open(fun, encoding="utf-8").read()

    out = [HEADER]
    for slug, name, blurb in SCENES:
        body = swift_block(src, slug)
        out.append("  {\n")
        out.append(f"    id: {js_string(slug)},\n")
        out.append(f"    name: {js_string(name)},\n")
        out.append(f"    blurb: {js_string(blurb)},\n")
        out.append("    body: " + js_template(body) + "\n")
        out.append("  },\n")
    out.append("];\n\n")
    out.append("module.exports = { SCENES };\n")

    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                        "src", "renderer", "lib", "vibresia-scenes.js")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as f:
        f.write("".join(out))
    print(f"wrote {len(SCENES)} scenes to {dest}")


if __name__ == "__main__":
    main()
