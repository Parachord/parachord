// The built-in visualiser: Vibresia scenes, drawn from the music Parachord
// is playing.
//
// These tests cover the parts that can be checked without a GPU: the scene
// list, the GLSL the renderer hands the driver, the audio the analyser
// derives, and the wiring in app.js. Whether the pixels look right is a
// question for a screen, not for a test; that the GLSL compiles is checked
// by scripts/check-vibresia-scenes.js, which uses a real compiler.
const fs = require('fs');
const path = require('path');

const { VibresiaRenderer, AudioAnalyser, idleAudio, toES } = require('../../src/renderer/lib/vibresia-visualizer');
const { SCENES } = require('../../src/renderer/lib/vibresia-scenes');

const ROOT = path.join(__dirname, '..', '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const appSrc = read('src/renderer/app.js');

describe('the visualiser scenes', () => {
  test('there are scenes, and each one names itself and says what it looks like', () => {
    expect(SCENES.length).toBeGreaterThan(0);
    for (const scene of SCENES) {
      expect(typeof scene.id).toBe('string');
      expect(scene.id.length).toBeGreaterThan(0);
      expect(typeof scene.name).toBe('string');
      expect(typeof scene.blurb).toBe('string');
    }
  });

  test('the scene ids are unique, so one scene cannot shadow another', () => {
    const ids = SCENES.map((s) => s.id);
    expect(new Set(ids).size).toBe(ids.length);
  });

  test('every scene is a full fragment shader that writes fragColor', () => {
    for (const scene of SCENES) {
      expect(scene.body).toMatch(/\bvoid\s+main\s*\(\s*\)/);
      expect(scene.body).toMatch(/fragColor/);
    }
  });

  test('the scenes are Vibresia\'s own, copied from its source, and the copy is regenerable', () => {
    // The extractor is what keeps the copy honest: it reads the Swift
    // source, so a scene can be refreshed rather than hand-edited here.
    const extractor = read('scripts/extract-vibresia-scenes.py');
    expect(extractor).toContain('FunShaders.swift');
    expect(extractor).toContain('vibresia-scenes.js');
    // And the generated file says so, so nobody edits it by hand.
    expect(read('src/renderer/lib/vibresia-scenes.js')).toMatch(/GENERATED by scripts\/extract-vibresia-scenes\.py/);
  });
});

describe('the GLSL the renderer hands the driver', () => {
  test('the prelude carries the uniforms a Vibresia scene reads', () => {
    const { PRELUDE } = require('../../src/renderer/lib/vibresia-visualizer');
    for (const name of [
      'uBass', 'uMid', 'uTreble', 'uBeat', 'uBeatStrength', 'uLevel',
      'uLevelSmooth', 'uBassSmooth', 'uActive', 'uBeats',
      'uScroll', 'uClock', 'uPresence', 'uTrackPos', 'uTrackDuration',
      'uTrackProgress', 'uTrackKnown', 'uKey', 'uMidiNote'
    ]) {
      expect(PRELUDE).toContain(`uniform float ${name};`);
    }
    // The spectrum is an array of 96 bands, not a scalar.
    expect(PRELUDE).toContain('uniform float uBands[96];');
    expect(PRELUDE).toContain('uniform int uGenre;');
    expect(PRELUDE).toContain('uniform vec2 uMouse;');
  });

  test('the prelude carries the helpers a scene calls without declaring them', () => {
    const { PRELUDE } = require('../../src/renderer/lib/vibresia-visualizer');
    for (const helper of [
      'screenP', 'pointerAt', 'pointerUV', 'aaw', 'hash11', 'hash21',
      'vnoise', 'fbm', 'bandAt', 'rot', 'sdCircle', 'sdEllipse', 'sdBox',
      'sdRoundBox', 'sdSeg', 'fill', 'dance', 'groove'
    ]) {
      expect(PRELUDE).toMatch(new RegExp(`\\b${helper}\\s*\\(`));
    }
  });

  test('the desktop GLSL is retargeted for WebGL2, which speaks GLSL ES', () => {
    // `#version 330 core` is rejected by a WebGL2 context, and a fragment
    // shader in GLSL ES has no default float precision. Both are fixed
    // here, or no scene would draw at all.
    const es = toES('#version 330 core\nvoid main() {}', true);
    expect(es.startsWith('#version 300 es')).toBe(true);
    expect(es).toContain('precision highp float;');
    expect(es).toContain('precision highp int;');
    // A vertex shader does not get the precision lines: GLSL ES allows
    // float precision to be declared, and the fragment stage is the one
    // that needs it.
    expect(toES('#version 330 core\nvoid main() {}', false)).not.toContain('precision highp float;');
  });

  test('a scene that will not compile says so in words, not as a blank frame', () => {
    const canvas = { getContext: () => null };
    const renderer = new VibresiaRenderer(canvas);
    // No WebGL2 at all: the reason is the reason.
    expect(renderer.setup(SCENES[0])).toEqual({ ok: false, error: 'no webgl2' });
  });
});

describe('the audio the scene is drawn with', () => {
  test('silence is quiet, not blank: the scene still draws', () => {
    const a = idleAudio(12);
    expect(a.level).toBe(0);
    expect(a.bass).toBe(0);
    // uActive is 0 in silence, so a scene that multiplies by it goes dark,
    // but the picture is still there.
    expect(a.active).toBe(0);
    expect(a.idle).toBe(1);
    expect(a.bands).toHaveLength(96);
    expect(a.beats).toBeGreaterThan(0);
  });

  test('an analyser with nothing attached reports nothing rather than throwing', () => {
    const analyser = new AudioAnalyser();
    expect(analyser.read(1)).toBeNull();
    expect(analyser.attach(null)).toBe(false);
    // Detaching something that was never attached is safe.
    expect(() => analyser.detach()).not.toThrow();
  });

  test('an analyser with no Web Audio cannot attach, and says so', () => {
    const analyser = new AudioAnalyser();
    const originalWindow = global.window;
    // No window at all: the module must load and behave under plain Node.
    delete global.window;
    expect(analyser.attach({ paused: false })).toBe(false);
    global.window = originalWindow;
  });

  test('the analyser reads the music and produces the ranges a scene expects', () => {
    const analyser = new AudioAnalyser();
    // A fake element and a fake Web Audio context, so the arithmetic can be
    // checked without a speaker.
    const bins = new Uint8Array(1024);
    analyser.bins = bins;
    analyser.hz = 44100 / 2048;
    analyser.element = { paused: false };
    analyser.analyser = {
      getByteFrequencyData: (target) => {
        // Energy in the bass band only, so the levels are predictable.
        const bassEnd = Math.floor(150 / analyser.hz);
        for (let i = 0; i < target.length; i++) target[i] = i < bassEnd ? 200 : 0;
      }
    };
    const a = analyser.read(4);
    expect(a).not.toBeNull();
    expect(a.bass).toBeGreaterThan(0.5);
    expect(a.level).toBeGreaterThan(0);
    expect(a.bands).toHaveLength(96);
    expect(a.active).toBe(1);
    expect(a.idle).toBe(0);
  });
});

describe('the visualiser in the app', () => {
  test('the panel is rendered from app.js, and only when it is open', () => {
    expect(appSrc).toContain("const { VisualizerPanel, allScenes: vibresiaScenes } = require('./components/visualizer-panel');");
    expect(appSrc).toContain('visualizerOpen && React.createElement(VisualizerPanel, {');
  });

  test('the scene comes from the element the current source plays through', () => {
    // The scene has to follow the track, not the app: the audio comes from
    // the element the resolver is playing through.
    expect(appSrc).toContain('audioElement: mediaElementFor(currentTrack?._activeResolver),');
  });

  test('the sidebar has a button that opens the visualiser', () => {
    expect(appSrc).toContain('onClick: () => setVisualizerOpen((v) => !v)');
    expect(appSrc).toContain("'Visualizer'");
  });

  test('the chosen scene is remembered, and only written once it has been read', () => {
    // Writing on mount with the default would overwrite the saved choice.
    expect(appSrc).toContain("window.electron.store.get('visualizer_scene')");
    expect(appSrc).toContain("window.electron.store.set('visualizer_scene', visualizerScene)");
    expect(appSrc).toContain('if (!cacheLoaded || !visualizerSceneLoaded || !window.electron?.store) return;');
  });

  test('a saved scene that no longer exists falls back rather than breaking the panel', () => {
    expect(appSrc).toContain('vibresiaScenes().some((s) => s.id === saved)');
  });
});
